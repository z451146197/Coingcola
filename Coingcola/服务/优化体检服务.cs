using Coingcola.模型;
using System;
using System.Collections.Generic;
using System.Globalization;

namespace Coingcola.服务
{
    /// <summary>
    /// 一键优化体检服务。
    /// 
    /// 当前策略：
    /// 1. 先做总控台骨架
    /// 2. 汇总已完成模块的关键信息
    /// 3. 输出“建议动作 + 快速跳转”
    /// 4. 暂不做复杂评分与批量执行
    /// </summary>
    public class 优化体检服务
    {
        private readonly 设备概览服务 _设备概览服务 = new();
        private readonly 运行状态服务 _运行状态服务 = new();
        private readonly 软件更新服务 _软件更新服务 = new();
        private readonly 常见修复服务 _常见修复服务 = new();
        private readonly 高级设置服务 _高级设置服务 = new();

        public 优化体检页面数据 获取页面数据()
        {
            var 设备概览 = _设备概览服务.获取设备概览();
            var 运行状态 = _运行状态服务.获取运行状态();

            double cpu = 解析百分比(运行状态.CPU当前负载);
            double memory = 解析百分比(运行状态.内存使用率);
            double disk = 解析百分比(运行状态.系统盘使用率);

            int 软件更新入口数 = _软件更新服务.获取更新列表().Count;
            int 常见修复动作数 = _常见修复服务.获取修复动作列表().Count;
            int 高级入口数 = _高级设置服务.获取入口列表().Count;
            bool winget可用 = _软件更新服务.系统支持Winget();

            var data = new 优化体检页面数据
            {
                页面标题 = "一键优化",
                页面结论 = 生成页面结论(cpu, memory, disk),
                副结论 = "当前页先整合已完成能力，帮助你快速判断该先看哪里、先处理什么。",
                设备名称 = 设备概览.设备名称,
                系统名称 = $"{设备概览.系统名称} · {设备概览.系统版本}",
                当前用户 = 设备概览.当前用户,
                权限状态 = 设备概览.权限状态,
                Winget状态 = winget可用 ? "已安装" : "未检测到"
            };

            data.摘要卡列表 = new List<优化体检摘要卡项>
            {
                new 优化体检摘要卡项
                {
                    标题 = "CPU 当前负载",
                    数值 = 运行状态.CPU当前负载,
                    说明 = 运行状态.CPU名称
                },
                new 优化体检摘要卡项
                {
                    标题 = "内存使用率",
                    数值 = 运行状态.内存使用率,
                    说明 = $"已用 {运行状态.内存已用} / 总量 {运行状态.内存总量}"
                },
                new 优化体检摘要卡项
                {
                    标题 = "系统盘使用率",
                    数值 = 运行状态.系统盘使用率,
                    说明 = $"{运行状态.系统盘名称} 可用 {运行状态.系统盘可用}"
                },
                new 优化体检摘要卡项
                {
                    标题 = "软件更新入口",
                    数值 = 软件更新入口数.ToString(),
                    说明 = winget可用 ? "支持系统更新与官网更新两种路径。" : "当前以官网更新为主。"
                },
                new 优化体检摘要卡项
                {
                    标题 = "常见修复动作",
                    数值 = 常见修复动作数.ToString(),
                    说明 = "已接入的低风险修复动作数量。"
                },
                new 优化体检摘要卡项
                {
                    标题 = "高级入口",
                    数值 = 高级入口数.ToString(),
                    说明 = "已聚合的高频高级系统入口数量。"
                }
            };

            data.建议列表 = 生成建议列表(cpu, memory, disk, winget可用);
            data.快捷入口列表 = 生成快捷入口列表();

            return data;
        }

        private List<优化体检建议项> 生成建议列表(double cpu, double memory, double disk, bool winget可用)
        {
            var list = new List<优化体检建议项>();

            if (cpu >= 70)
            {
                list.Add(new 优化体检建议项
                {
                    标题 = "优先检查 CPU 负载",
                    说明 = "当前 CPU 已进入较高占用区间，建议先去“运行状态”确认是否存在异常占用。",
                    按钮文本 = "查看运行状态",
                    跳转标识 = "我的电脑|运行状态"
                });
            }

            if (memory >= 75)
            {
                list.Add(new 优化体检建议项
                {
                    标题 = "关注内存压力",
                    说明 = "当前内存占用偏高，建议先看“运行状态”，必要时再结合软件与启动项处理。",
                    按钮文本 = "查看运行状态",
                    跳转标识 = "我的电脑|运行状态"
                });
            }

            if (disk >= 85)
            {
                list.Add(new 优化体检建议项
                {
                    标题 = "系统盘空间偏紧",
                    说明 = "当前系统盘占用较高，建议先看“运行状态”与“详细配置”，再决定是否清理。",
                    按钮文本 = "查看详细配置",
                    跳转标识 = "我的电脑|详细配置"
                });
            }

            list.Add(new 优化体检建议项
            {
                标题 = "检查软件更新",
                说明 = winget可用
                    ? "当前已支持系统更新，建议优先查看软件更新页。"
                    : "当前未检测到 winget，建议以官网更新为主检查常用软件。",
                按钮文本 = "查看软件更新",
                跳转标识 = "软件中心|软件更新"
            });

            list.Add(new 优化体检建议项
            {
                标题 = "准备常见修复入口",
                说明 = "如果你当前遇到卡顿、图标异常、网络问题，可直接进入常见修复页。",
                按钮文本 = "查看常见修复",
                跳转标识 = "电脑优化|常见修复"
            });

            list.Add(new 优化体检建议项
            {
                标题 = "按推荐值优化系统习惯",
                说明 = "如果机器本身没故障，但用起来不顺手，优先去“常用设置”。",
                按钮文本 = "去优化",
                跳转标识 = "电脑优化|常用设置"
            });

            return list;
        }

        private List<优化体检快捷入口项> 生成快捷入口列表()
        {
            return new List<优化体检快捷入口项>
            {
                new 优化体检快捷入口项
                {
                    名称 = "电脑概览",
                    简介 = "快速看整机状态",
                    跳转标识 = "我的电脑|电脑概览"
                },
                new 优化体检快捷入口项
                {
                    名称 = "运行状态",
                    简介 = "看 CPU/内存/系统盘",
                    跳转标识 = "我的电脑|运行状态"
                },
                new 优化体检快捷入口项
                {
                    名称 = "详细配置",
                    简介 = "核对完整配置",
                    跳转标识 = "我的电脑|详细配置"
                },
                new 优化体检快捷入口项
                {
                    名称 = "软件更新",
                    简介 = "检查更新入口",
                    跳转标识 = "软件中心|软件更新"
                },
                new 优化体检快捷入口项
                {
                    名称 = "常见修复",
                    简介 = "处理常见问题",
                    跳转标识 = "电脑优化|常见修复"
                },
                new 优化体检快捷入口项
                {
                    名称 = "常用设置",
                    简介 = "按推荐值优化习惯",
                    跳转标识 = "电脑优化|常用设置"
                }
            };
        }

        private string 生成页面结论(double cpu, double memory, double disk)
        {
            if (cpu >= 90 || memory >= 90 || disk >= 95)
            {
                return "当前设备存在高占用风险，建议优先查看运行状态与存储空间。";
            }

            if (cpu >= 70 || memory >= 75 || disk >= 85)
            {
                return "当前设备整体可用，但已有部分资源进入较高占用区间，建议做一次轻量处理。";
            }

            return "当前设备整体状态基本正常，可以按需处理软件更新、系统习惯和常见小问题。";
        }

        private double 解析百分比(string 文本)
        {
            if (string.IsNullOrWhiteSpace(文本))
            {
                return 0;
            }

            string value = 文本.Replace("%", "").Trim();
            return double.TryParse(value, NumberStyles.Any, CultureInfo.InvariantCulture, out double result)
                ? result
                : 0;
        }
    }
}